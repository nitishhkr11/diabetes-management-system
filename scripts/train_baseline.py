"""Train, compare, select, evaluate, explain and save - one command.

    python scripts/train_baseline.py              # reproduce the original three-model baseline
    python scripts/train_baseline.py --quick      # skip the slow extras (bootstrap, SHAP figures)

Order of work (every arrow of the architecture diagram is one block below):
  load + validate -> stratified split -> cross-validate 3 models on the TRAINING part
  -> select by the rule -> fit -> evaluate ONCE on the test part -> threshold study
  -> figures + SHAP -> save model files + model_card.json
"""
import argparse
import json
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import matplotlib  # noqa: E402

matplotlib.use("Agg")

import pandas as pd  # noqa: E402

from src import config as C  # noqa: E402
from src import modeling as M  # noqa: E402
from src import plots as P  # noqa: E402
from src.data_validation import canonical_sha256, load_dataset, sha256_file  # noqa: E402
from src.explain import PatientExplainer  # noqa: E402
from src.predict import save_artifacts  # noqa: E402
from src.preprocessing import split_data, training_profile  # noqa: E402


def say(msg=""):
    print(msg, flush=True)


def write_model_card(card: dict, path: Path) -> None:
    """Write human-readable release metadata from the same measured run."""
    test_rows = card["test_table"]
    cv_rows = {row["model"]: row for row in card["cv_table"]}
    lines = [
        "# Model card", "", "Generated by scripts/train_baseline.py from the checked-in benchmark.", "",
        "## Intended use", "", card["intended_use"], "",
        "## Training data", "",
        f"- Rows: {card['dataset']['rows']} (stratified train/test split {card['test_size']:.0%} test)",
        f"- Raw SHA-256: `{card['dataset']['raw_sha256']}`",
        f"- Canonical SHA-256: `{card['dataset']['canonical_sha256']}`",
        f"- Population scope: {card['population']}", "",
        "## Method", "",
        "Zero-to-missing conversion, median imputation and scaling are contained in each saved scikit-learn pipeline. Model selection uses stratified training-only cross-validation by ROC-AUC, then F1, then accuracy within the declared tolerance; the simplest model breaks any remaining tie. The untouched test split is used for final metrics.", "",
        f"Selected model: **{card['selected_model']}**  ",
        f"Model version: `{card['model_version']}`  ",
        f"Trained at: `{card['trained_at']}`  ",
        f"Runtime: Python {card['python_version']}, scikit-learn {card['sklearn_version']}", "",
        "## Cross-validation and held-out results", "",
        "| Model | CV ROC-AUC mean ± SD | Test accuracy | Precision | Recall | F1 | ROC-AUC | Brier |",
        "|---|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for row in test_rows:
        cv = cv_rows[row["model"]]
        lines.append("| {} | {:.3f} ± {:.3f} | {:.3f} | {:.3f} | {:.3f} | {:.3f} | {:.3f} | {:.3f} |".format(
            row["model"], cv["roc_auc_mean"], cv["roc_auc_std"], row["accuracy"], row["precision"],
            row["recall"], row["f1"], row["roc_auc"], row["brier"]))
    lines.extend(["", "## Artifact files", "", "| Model | File | SHA-256 |", "|---|---|---|"])
    for name, meta in card["files"].items():
        lines.append(f"| {name} | `{meta['file']}` | `{meta['sha256']}` |")
    lines.extend(["", "## Limitations", "",
        "This small historical dataset has narrow demographic coverage and substantial missing-value codes. No external validation, subgroup fairness study or clinical calibration study was performed. The outcome is not a future diagnosis. Scores and SHAP explanations must not guide clinical care.", "",
        f"The brief targets are project aspirations. Held-out target check: {sum(bool(x['met_on_test']) for x in card['targets'])}/{len(card['targets'])} met. See `reports/targets_check.csv`.", ""])
    path.write_text("\n".join(lines), encoding="utf-8")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--data", default=str(C.DATA_PATH))
    ap.add_argument("--models-dir", default=str(C.MODELS_DIR))
    ap.add_argument("--reports-dir", default=str(C.REPORTS_DIR))
    ap.add_argument("--model-card", default=str(Path(__file__).resolve().parents[1] / "docs" / "MODEL_CARD.md"))
    ap.add_argument("--lenient", action="store_true", help="accept a dataset that is not the verified Pima file")
    ap.add_argument("--quick", action="store_true", help="skip bootstrap intervals and SHAP figures")
    args = ap.parse_args(argv)
    t0 = time.time()
    reports = Path(args.reports_dir)
    figs = reports / "figures"
    reports.mkdir(parents=True, exist_ok=True)

    # 1 -- load + validate ---------------------------------------------------
    say("[1/8] Loading and validating the dataset")
    df = load_dataset(args.data, strict=not args.lenient)
    raw_hash, canon_hash = sha256_file(args.data), canonical_sha256(df)
    say(f"      {len(df)} rows, class counts {df[C.TARGET].value_counts().to_dict()}, canonical SHA-256 {canon_hash[:16]}...")

    # 2 -- split ---------------------------------------------------------------
    say("[2/8] Stratified split 80:20 (random_state=%d)" % C.RANDOM_STATE)
    X_train, X_test, y_train, y_test = split_data(df)
    say(f"      train {len(X_train)} rows ({y_train.mean():.1%} positive) | test {len(X_test)} rows ({y_test.mean():.1%} positive)")

    # 3 -- cross-validation on the training part --------------------------------
    say("[3/8] 5-fold cross-validation on the training part")
    cv_table = M.cross_validate_models(X_train, y_train)
    cv_table.to_csv(reports / "cv_results.csv", index=False)
    say(cv_table[["model", "roc_auc_mean", "roc_auc_std", "f1_mean", "accuracy_mean", "recall_mean"]].round(4).to_string(index=False))

    # 4 -- selection -----------------------------------------------------------
    say("[4/8] Model selection (ROC-AUC, then F1, then Accuracy; ties within %.3f)" % C.TIE_TOLERANCE)
    selected, log = M.select_best_model(cv_table)
    say("\n".join("      " + line for line in log))

    # 5 -- fit + test evaluation (the test part is used only here) ----------------
    say("[5/8] Fitting all three models on the training part and scoring the test part once")
    fitted = M.fit_models(X_train, y_train)
    test_table = M.evaluate_models(fitted, X_test, y_test)
    test_table.to_csv(reports / "test_metrics.csv", index=False)
    say(test_table[["model", "accuracy", "precision", "recall", "f1", "roc_auc", "brier"]].round(4).to_string(index=False))
    as_cv = test_table.rename(columns={m: f"{m}_mean" for m in ("roc_auc", "f1", "accuracy")})
    test_pick, _ = M.select_best_model(as_cv)
    say(f"      (same rule applied to TEST scores would pick: {test_pick} -> "
        f"{'same as' if test_pick == selected else 'DIFFERENT from'} the cross-validation pick)")
    probas = {n: p.predict_proba(X_test)[:, 1] for n, p in fitted.items()}

    # 6 -- uncertainty + project targets -----------------------------------------
    say("[6/8] Uncertainty and the project targets")
    sel_row = test_table[test_table.model == selected].iloc[0]
    sel_cv = cv_table[cv_table.model == selected].iloc[0]
    ci_rows = []
    if not args.quick:
        for name, p in probas.items():
            for metric, (lo, hi) in M.bootstrap_ci(y_test, p).items():
                ci_rows.append({"model": name, "metric": metric, "lo": lo, "hi": hi})
        pd.DataFrame(ci_rows).to_csv(reports / "test_bootstrap_ci.csv", index=False)
    targets = []
    for metric, goal in C.PROJECT_TARGETS.items():
        targets.append({"metric": metric, "target": goal, "test_value": float(sel_row[metric]),
                        "cv_mean": float(sel_cv[f"{metric}_mean"]), "met_on_test": bool(sel_row[metric] >= goal)})
    pd.DataFrame(targets).to_csv(reports / "targets_check.csv", index=False)
    for t in targets:
        say(f"      target {t['metric']:9s} >= {t['target']:.2f}: test {t['test_value']:.3f} (cv {t['cv_mean']:.3f}) -> "
            f"{'MET' if t['met_on_test'] else 'NOT met'}")

    # 7 -- threshold study (uses out-of-fold scores of the TRAINING part only) --------
    say("[7/8] Threshold study for the selected model")
    oof = M.oof_probabilities(M.get_models()[selected], X_train, y_train)
    thr_table = M.threshold_table(y_train, oof)
    thr_table.to_csv(reports / "threshold_table_oof.csv", index=False)
    thr_recall = M.threshold_for_recall(thr_table, C.PROJECT_TARGETS["recall"])
    op = {"goal_recall": C.PROJECT_TARGETS["recall"], "threshold": thr_recall}
    if thr_recall is not None:
        op["test_metrics_at_threshold"] = {k: v for k, v in M.compute_metrics(y_test, probas[selected], thr_recall).items()}
        m = op["test_metrics_at_threshold"]
        say(f"      highest OOF threshold with recall >= {C.PROJECT_TARGETS['recall']}: {thr_recall:.2f} -> test recall "
            f"{m['recall']:.3f}, precision {m['precision']:.3f}, F1 {m['f1']:.3f}, accuracy {m['accuracy']:.3f}")
    (reports / "operating_point.json").write_text(json.dumps(op, indent=2))

    # 8 -- figures, SHAP, artifacts ----------------------------------------------
    say("[8/8] Figures, SHAP and saving the model files")
    P.save(P.plot_roc(y_test, probas), figs / "roc_test.png")
    cms = {n: [[int(r.tn), int(r.fp)], [int(r.fn), int(r.tp)]] for n, r in test_table.set_index("model").iterrows()}
    P.save(P.plot_confusion_panel(cms), figs / "confusion_test.png")
    P.save(P.plot_cv_scores(cv_table), figs / "cv_roc_auc.png")
    P.save(P.plot_calibration(y_test, probas), figs / "calibration_test.png")
    P.save(P.plot_threshold(thr_table, C.DECISION_THRESHOLD, f"{selected}: scores vs threshold (out-of-fold, training part)"),
           figs / "threshold_tradeoff.png")

    explainer = PatientExplainer(fitted[selected], X_train)
    if not args.quick:
        import matplotlib.pyplot as plt
        import shap
        P.save(P.plot_global_importance(explainer.global_importance(X_test), units=explainer.units),
               figs / "shap_global_bar.png")
        explainer.global_importance(X_test).to_csv(reports / "shap_global_importance.csv", index=False)
        shap.plots.beeswarm(explainer.explanation(X_test), show=False, max_display=8)
        P.save(plt.gcf(), figs / "shap_beeswarm.png")
        order = probas[selected].argsort()
        for tag, idx in (("lowest", order[0]), ("highest", order[-1])):
            e = explainer.explain_one(X_test.iloc[[idx]])
            P.save(P.plot_contributions(e), figs / f"shap_patient_{tag}.png")

    card = {
        "dataset": {"raw_sha256": raw_hash, "canonical_sha256": canon_hash, "rows": len(df)},
        "random_state": C.RANDOM_STATE, "test_size": C.TEST_SIZE, "cv_folds": C.CV_FOLDS,
        "threshold": C.DECISION_THRESHOLD, "tie_tolerance": C.TIE_TOLERANCE,
        "features": C.FEATURES, "profile": training_profile(X_train),
        "cv_table": cv_table.to_dict("records"), "test_table": test_table.to_dict("records"),
        "selection_log": log, "test_pick": test_pick, "targets": targets, "operating_point": op,
        "intended_use": "Educational decision-support prototype. NOT a diagnostic device.",
        "population": "Women aged 21+ of Pima heritage (Phoenix, Arizona). Not validated for anyone else.",
    }
    card = save_artifacts(fitted, selected, card, args.models_dir)
    model_card_path = Path(args.model_card)
    model_card_path.parent.mkdir(parents=True, exist_ok=True)
    write_model_card(card, model_card_path)
    say(f"      saved models to {args.models_dir} (model_version {card['model_version']})")
    say(f"Done in {time.time() - t0:.0f} s.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
